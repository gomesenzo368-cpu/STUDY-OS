create table if not exists public.revision_questions (
  id bigint generated by default as identity primary key,
  course_id bigint not null,
  question_type text not null,
  question_text text not null,
  choices jsonb,
  explanation text,
  difficulty text not null default 'medium',
  position integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint revision_questions_course_fk
    foreign key (course_id) references public.courses(id) on delete cascade,
  constraint revision_questions_type_check
    check (question_type in ('multiple_choice', 'true_false', 'short_answer')),
  constraint revision_questions_difficulty_check
    check (difficulty in ('easy', 'medium', 'hard')),
  constraint revision_questions_position_check
    check (position >= 0),
  constraint revision_questions_choices_check
    check (
      (question_type = 'multiple_choice'
        and choices is not null
        and jsonb_typeof(choices) = 'array')
      or (question_type in ('true_false', 'short_answer') and choices is null)
    )
);

create table if not exists public.revision_question_keys (
  question_id bigint primary key,
  correct_answer jsonb not null,
  constraint revision_question_keys_question_fk
    foreign key (question_id)
    references public.revision_questions(id)
    on delete cascade
);

create table if not exists public.revision_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  course_id bigint,
  question_ids_snapshot bigint[] not null,
  status text not null,
  total_questions integer not null,
  correct_answers integer not null,
  score numeric(5, 2) not null,
  started_at timestamptz not null,
  completed_at timestamptz,
  duration_seconds integer,
  created_at timestamptz not null default now(),
  constraint revision_sessions_user_fk
    foreign key (user_id) references auth.users(id) on delete cascade,
  constraint revision_sessions_course_fk
    foreign key (course_id) references public.courses(id) on delete set null,
  constraint revision_sessions_status_check
    check (status in ('in_progress', 'completed', 'abandoned')),
  constraint revision_sessions_counts_check
    check (
      total_questions >= 0
      and correct_answers >= 0
      and correct_answers <= total_questions
      and total_questions = cardinality(question_ids_snapshot)
      and array_position(question_ids_snapshot, null) is null
    ),
  constraint revision_sessions_score_check
    check (
      score between 0 and 100
      and score = case
        when total_questions = 0 then 0::numeric
        else round(correct_answers::numeric * 100 / total_questions, 2)
      end
    ),
  constraint revision_sessions_duration_check
    check (duration_seconds is null or duration_seconds >= 0),
  constraint revision_sessions_terminal_time_check
    check (
      (status = 'in_progress' and completed_at is null and duration_seconds is null)
      or (status in ('completed', 'abandoned')
        and completed_at is not null
        and duration_seconds is not null)
    )
);

create table if not exists public.revision_answers (
  id bigint generated by default as identity primary key,
  session_id bigint not null,
  question_id bigint,
  question_text_snapshot text not null,
  question_type_snapshot text not null,
  choices_snapshot jsonb,
  answer jsonb not null,
  is_correct boolean not null,
  answered_at timestamptz not null default now(),
  constraint revision_answers_session_fk
    foreign key (session_id)
    references public.revision_sessions(id)
    on delete cascade,
  constraint revision_answers_question_fk
    foreign key (question_id)
    references public.revision_questions(id)
    on delete set null,
  constraint revision_answers_type_check
    check (question_type_snapshot in ('multiple_choice', 'true_false', 'short_answer')),
  constraint revision_answers_choices_check
    check (
      (question_type_snapshot = 'multiple_choice'
        and choices_snapshot is not null
        and jsonb_typeof(choices_snapshot) = 'array')
      or (question_type_snapshot in ('true_false', 'short_answer')
        and choices_snapshot is null)
    ),
  constraint revision_answers_session_question_key
    unique (session_id, question_id)
);

create index if not exists revision_questions_course_position_idx
  on public.revision_questions (course_id, position, id);
create index if not exists revision_sessions_user_started_idx
  on public.revision_sessions (user_id, started_at desc);
create index if not exists revision_sessions_course_idx
  on public.revision_sessions (course_id);
create index if not exists revision_answers_question_idx
  on public.revision_answers (question_id);

