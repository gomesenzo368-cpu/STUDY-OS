create or replace function public.sync_planning_series_year_dates()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  school_year_start date;
  school_year_end date;
begin
  select school_year.starts_on, school_year.ends_on
  into school_year_start, school_year_end
  from public.planning_years as school_year
  where school_year.id = new.year_id
    and school_year.user_id = new.user_id;

  if school_year_start is null or school_year_end is null then
    raise exception 'Année scolaire inaccessible.' using errcode = '23503';
  end if;

  if new.recurrence = 'weekly' then
    new.starts_on := school_year_start;
    new.ends_on := school_year_end;
  elsif new.recurrence = 'once' then
    if new.starts_on < school_year_start or new.starts_on > school_year_end then
      raise exception 'La séance ponctuelle doit se trouver dans l’année scolaire.' using errcode = '23514';
    end if;
    new.ends_on := null;
  end if;

  return new;
end;
$$;

drop trigger if exists planning_series_sync_year_dates on public.planning_series;
create trigger planning_series_sync_year_dates
before insert or update of year_id, recurrence, starts_on, ends_on on public.planning_series
for each row execute function public.sync_planning_series_year_dates();

create or replace function public.sync_planning_year_series_dates()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if exists (
    select 1
    from public.planning_series as series
    where series.year_id = new.id
      and series.user_id = new.user_id
      and series.recurrence = 'once'
      and (series.starts_on < new.starts_on or series.starts_on > new.ends_on)
  ) then
    raise exception 'Une séance ponctuelle se trouverait hors de la nouvelle année scolaire.' using errcode = '23514';
  end if;

  update public.planning_series as series
  set starts_on = new.starts_on,
      ends_on = new.ends_on
  where series.year_id = new.id
    and series.user_id = new.user_id
    and series.recurrence = 'weekly';

  return new;
end;
$$;

drop trigger if exists planning_years_sync_series_dates on public.planning_years;
create trigger planning_years_sync_series_dates
after update of starts_on, ends_on on public.planning_years
for each row execute function public.sync_planning_year_series_dates();

