create table if not exists public.planning_years (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null default 'Année scolaire',
  starts_on date not null,
  ends_on date not null,
  time_zone text not null default 'UTC',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint planning_years_date_order check (starts_on <= ends_on),
  constraint planning_years_id_user_key unique (id, user_id)
);

create table if not exists public.planning_calendar_blocks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  year_id bigint not null,
  kind text not null check (kind in ('break', 'holiday')),
  name text,
  starts_on date not null,
  ends_on date not null,
  description text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint planning_calendar_blocks_date_order check (starts_on <= ends_on),
  constraint planning_calendar_blocks_holiday_date check (kind <> 'holiday' or starts_on = ends_on),
  constraint planning_calendar_blocks_year_user_fk
    foreign key (year_id, user_id)
    references public.planning_years(id, user_id)
    on delete cascade
);

create table if not exists public.planning_series (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  year_id bigint not null,
  entry_type text not null default 'class',
  title text not null,
  subject_id bigint references public.subjects(id) on delete set null,
  teacher text,
  room text,
  day_of_week smallint not null check (day_of_week between 1 and 7),
  recurrence text not null check (recurrence in ('weekly', 'once')),
  week_pattern text not null default 'all' check (week_pattern in ('all', 'even', 'odd')),
  starts_on date not null,
  ends_on date,
  start_time time not null,
  end_time time not null,
  color_key text,
  icon_key text,
  status text not null default 'active' check (status in ('active', 'cancelled')),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint planning_series_time_order check (start_time < end_time),
  constraint planning_series_recurrence_dates check (
    (recurrence = 'weekly' and ends_on is not null and starts_on <= ends_on)
    or (recurrence = 'once' and ends_on is null)
  ),
  constraint planning_series_year_user_fk
    foreign key (year_id, user_id)
    references public.planning_years(id, user_id)
    on delete cascade,
  constraint planning_series_id_user_key unique (id, user_id)
);

create table if not exists public.planning_exceptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  series_id bigint not null,
  occurrence_date date not null,
  status text not null check (status in ('cancelled', 'modified')),
  override_date date,
  overrides jsonb not null default '{}'::jsonb check (jsonb_typeof(overrides) = 'object'),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint planning_exceptions_series_user_fk
    foreign key (series_id, user_id)
    references public.planning_series(id, user_id)
    on delete cascade,
  constraint planning_exceptions_unique_occurrence unique (series_id, occurrence_date)
);

